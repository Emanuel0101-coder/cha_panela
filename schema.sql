CREATE TABLE IF NOT EXISTS convidados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_convidados_nome_unico
ON convidados (lower(trim(nome)));


CREATE TABLE IF NOT EXISTS tokens_convidados (
    token_hash TEXT PRIMARY KEY,
    convidado_id BIGINT NOT NULL
        REFERENCES convidados(id)
        ON DELETE CASCADE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS presentes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    reservado INTEGER NOT NULL DEFAULT 0
        CHECK (reservado >= 0),
    quantidade_total INTEGER NOT NULL DEFAULT 1
        CHECK (quantidade_total >= 1)
);


CREATE TABLE IF NOT EXISTS reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    convidado_id BIGINT NOT NULL
        REFERENCES convidados(id)
        ON DELETE CASCADE,
    presente_id BIGINT NOT NULL
        REFERENCES presentes(id)
        ON DELETE CASCADE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_reserva_convidado_presente
        UNIQUE (convidado_id, presente_id)
);


CREATE INDEX IF NOT EXISTS idx_reservas_presente_id
ON reservas (presente_id);


CREATE INDEX IF NOT EXISTS idx_reservas_convidado_id
ON reservas (convidado_id);